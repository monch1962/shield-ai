#!/usr/bin/env python3
"""Interactive explorer over the SHIELD-AI graph of record.

Reads `assets/shield-ai-explorer-graph.json` (generated by
`tools/generate_explorer_graph.py`) and provides drill-down, faceted, and
graph-path views over the incidents / controls / pillars / gaps / exploits /
REGO-policy links. Designed for maintainers navigating the framework quickly,
and as the query engine behind the interactive HTML explorer.

Usage:
    python3 tools/explore.py control MS-11        # drill into a control
    python3 tools/explore.py incident INC-33      # drill into an incident
    python3 tools/explore.py pillar EE            # facet: list a pillar's controls
    python3 tools/explore.py path INC-29 MS-11    # shortest link path between two nodes
    python3 tools/explore.py query --pillar EE --severity escalation
                                                  # facet on arbitrary attributes
"""
import argparse
import json
import os
import sys
import collections

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
GRAPH = os.path.join(ROOT, "assets", "shield-ai-explorer-graph.json")
GENERATOR = os.path.join(ROOT, "tools", "generate_explorer_graph.py")


def load_graph():
    if not os.path.exists(GRAPH):
        # regenerate from sources if the committed graph is missing
        import subprocess
        subprocess.run([sys.executable, GENERATOR, "--write"], cwd=ROOT, check=True,
                       capture_output=True)
    with open(GRAPH, encoding="utf-8") as f:
        return json.load(f)


# --- pure query helpers (unit-testable) -------------------------------------

def _find(g, kind, node_id):
    for item in g[kind]:
        if item["id"] == node_id:
            return item
    return None


def describe_control(g, cid):
    c = _find(g, "controls", cid)
    if not c:
        raise KeyError(f"control {cid} not in graph")
    return c


def describe_incident(g, iid):
    i = _find(g, "incidents", iid)
    if not i:
        raise KeyError(f"incident {iid} not in graph")
    return i


def controls_by_pillar(g, pillar):
    p = _find(g, "pillars", pillar)
    return list(p["controls"]) if p else []


def unique_pillars_for(g, kind, node_id):
    """The distinct pillars linked (directly or transitively) to a node."""
    if kind == "control":
        c = _find(g, "controls", node_id)
        return {c["pillar"]} if c else set()
    if kind == "incident":
        i = _find(g, "incidents", node_id)
        pillars = set()
        for cid in i["controls"]:
            c = _find(g, "controls", cid)
            if c:
                pillars.add(c["pillar"])
        return pillars
    return set()


def faceted_search(g, **filters):
    """Filter controls by control-schema attributes (pillar, etc.)."""
    out = []
    for c in g["controls"]:
        ok = True
        for k, v in filters.items():
            if k == "pillar" and c.get("pillar") != v:
                ok = False
            elif c.get(k) != v:
                ok = False
        if ok:
            out.append(c["id"])
    return out


def shortest_path(g, start, end):
    """BFS over the derived edges between two node ids (same or cross-kind)."""
    if start == end:
        return [start]
    adj = collections.defaultdict(list)
    for e in g["edges"]:
        adj[e["from"]].append(e["to"])
        adj[e["to"]].append(e["from"])
    if start not in adj:
        return None
    prev = {start: None}
    q = collections.deque([start])
    while q:
        cur = q.popleft()
        if cur == end:
            break
        for nb in adj.get(cur, []):
            if nb not in prev:
                prev[nb] = cur
                q.append(nb)
    if end not in prev:
        return None
    path = []
    cur = end
    while cur is not None:
        path.append(cur)
        cur = prev[cur]
    return list(reversed(path))


# --- CLI rendering -----------------------------------------------------------

def _print_control(c):
    print(f"\nCONTROL {c['id']}: {c['title']}")
    print(f"  pillar     : {c['pillar']} ({c.get('pillar_name','')})")
    print(f"  rego       : {c['rego'] or '(none)'}")
    print(f"  incidents  : {', '.join(c['incidents']) or '(none)'}")
    print(f"  gaps       : {', '.join(c['gap_ids']) or '(none)'}")
    print(f"  exploits   : {', '.join(c['exploit_ids']) or '(none)'}")
    if c.get("description"):
        print(f"  desc       : {c['description'][:140]}{'...' if len(c['description'])>140 else ''}")


def _print_incident(i):
    print(f"\nINCIDENT {i['id']}: {i['title']}")
    print(f"  severity   : {i['severity']}")
    print(f"  controls   : {', '.join(i['controls']) or '(none)'}")
    print(f"  gaps       : {', '.join(i['gap_ids']) or '(none)'}")


def _print_pillar(g, pid):
    p = _find(g, "pillars", pid)
    if not p:
        print(f"pillar {pid} not found"); return
    print(f"\nPILLAR {p['id']}: {p['name']}  ({len(p['controls'])} controls)")
    for cid in p["controls"]:
        c = _find(g, "controls", cid)
        print(f"  {cid}: {c['title']}")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("control").add_argument("id")
    sub.add_parser("incident").add_argument("id")
    sub.add_parser("pillar").add_argument("id")
    p = sub.add_parser("path"); p.add_argument("a"); p.add_argument("b")
    q = sub.add_parser("query"); q.add_argument("--pillar"); q.add_argument("--severity")
    args = ap.parse_args()

    g = load_graph()
    if args.cmd == "control":
        try: _print_control(describe_control(g, args.id))
        except KeyError as e: print(str(e)); return 1
    elif args.cmd == "incident":
        try: _print_incident(describe_incident(g, args.id))
        except KeyError as e: print(str(e)); return 1
    elif args.cmd == "pillar":
        _print_pillar(g, args.id)
    elif args.cmd == "path":
        path = shortest_path(g, args.a, args.b)
        if path is None:
            print(f"no path between {args.a} and {args.b}")
        else:
            print(f"\npath: {' -> '.join(path)}")
    elif args.cmd == "query":
        filt = {k: v for k, v in vars(args).items()
                if k in ("pillar", "severity") and v}
        ids = faceted_search(g, **filt)
        print(f"\n{len(ids)} controls match:")
        for cid in ids:
            c = _find(g, "controls", cid)
            print(f"  {cid}: {c['title']}")
    else:
        ap.print_help()
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())